#!/usr/bin/env python3
"""
make_secrets.py - write secrets.h for every ESP32 sketch, from the .env file.

The sketches never contain your WiFi password, broker address or OTA password.
They #include "secrets.h", which this script generates and git ignores.
Run it once after filling in .env, and again whenever you change .env.

    python3 host/make_secrets.py
"""

import os
import sys

from envfile import ENV_FILE, REPO_ROOT, is_placeholder, load_env

# .env name -> name the sketches use
SECRETS = {
    "WIFI_SSID": "SECRET_WIFI_SSID",
    "WIFI_PASSWORD": "SECRET_WIFI_PASSWORD",
    "MQTT_HOST": "SECRET_MQTT_HOST",
    "OTA_PASSWORD": "SECRET_OTA_PASSWORD",
}


def c_string(value):
    """Quote a value as a C string literal."""
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    if not load_env():
        sys.exit(f"No .env file. Copy .env.example to {ENV_FILE} and fill it in.")

    values = {key: os.environ.get(key, "") for key in SECRETS}
    missing = [key for key, value in values.items() if is_placeholder(value)]
    if missing:
        sys.exit(f"Fill in these values in {ENV_FILE}: {', '.join(missing)}")
    bad = [key for key, value in values.items() if "\n" in value or "\r" in value]
    if bad:
        sys.exit(f"These values contain a line break: {', '.join(bad)}")

    lines = [
        "// Generated by host/make_secrets.py from .env - do not edit or commit.",
        "// .gitignore keeps this file out of git.",
        "#pragma once",
        "",
    ]
    lines += [f"#define {SECRETS[key]} {c_string(value)}" for key, value in values.items()]
    content = "\n".join(lines) + "\n"

    sketches = sorted(
        ino.parent
        for ino in (REPO_ROOT / "firmware").rglob("*.ino")
        if '"secrets.h"' in ino.read_text()
    )
    if not sketches:
        sys.exit("No sketches use secrets.h.")
    for folder in sketches:
        (folder / "secrets.h").write_text(content)
        print(f"wrote {(folder / 'secrets.h').relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
